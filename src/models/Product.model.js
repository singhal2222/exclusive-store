// FILE LOCATION: src/models/Product.model.js

import mongoose from "mongoose";

const productSchema = new mongoose.Schema(
  {
    // ============================================================
    // PRODUCT DETAILS
    // ============================================================

    name: {
      type: String,
      required: [true, "Product name is required"],
      trim: true,
      minlength: [2, "Product name must be at least 2 characters"],
      maxlength: [150, "Product name must not exceed 150 characters"],
    },

    description: {
      type: String,
      required: [true, "Product description is required"],
      trim: true,
      minlength: [10, "Description must be at least 10 characters"],
      maxlength: [2000, "Description must not exceed 2000 characters"],
    },

    // Category reference
    category: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Category",
      required: [true, "Category is required"],
    },

    // ============================================================
    // PRICING
    // ============================================================

    // Final selling price.
    // Automatically calculated when originalPrice is provided.
    price: {
      type: Number,
      required: [true, "Price is required"],
      min: [0, "Price cannot be negative"],
      validate: {
        validator: Number.isFinite,
        message: "Price must be a valid number",
      },
    },

    // Price before discount
    originalPrice: {
      type: Number,
      default: null,
      min: [0, "Original price cannot be negative"],
      validate: {
        validator(value) {
          return value == null || Number.isFinite(value);
        },
        message: "Original price must be a valid number",
      },
    },

    // Discount percentage entered by the admin
    discountPercentage: {
      type: Number,
      default: 0,
      min: [0, "Discount cannot be less than 0%"],
      max: [100, "Discount cannot exceed 100%"],
      validate: {
        validator: Number.isFinite,
        message: "Discount must be a valid number",
      },
    },

    // ============================================================
    // INVENTORY
    // ============================================================

    stock: {
      type: Number,
      required: [true, "Stock quantity is required"],
      default: 0,
      min: [0, "Stock cannot be negative"],
      validate: [
        {
          validator: Number.isFinite,
          message: "Stock must be a valid number",
        },
        {
          validator: Number.isInteger,
          message: "Stock must be a whole number",
        },
      ],
    },

    // ============================================================
    // RATING (COMPUTED ONLY)
    // ============================================================
    //
    // This value is COMPUTED AUTOMATICALLY from approved reviews.
    //
    // The admin API explicitly ignores any incoming `rating` value
    // on product create/update. Recalculation happens in the review
    // APIs whenever a review's status changes.
    //
    // Stores the rounded average (1 decimal place) of approved
    // reviews, or 0 when there are no approved reviews yet.
    //
    // ============================================================

    rating: {
      type: Number,
      default: 0,
      min: [0, "Rating cannot be less than 0"],
      max: [5, "Rating cannot be greater than 5"],
      validate: {
        validator: Number.isFinite,
        message: "Rating must be a valid number",
      },
    },

    // ============================================================
    // REVIEW COUNT (COMPUTED ONLY)
    // ============================================================
    //
    // Number of APPROVED reviews for this product.
    //
    // Used by the storefront to decide whether to display a
    // numeric rating or "No reviews yet". Also useful for sorting
    // and filtering.
    //
    // ============================================================

    reviewCount: {
      type: Number,
      default: 0,
      min: [0, "Review count cannot be negative"],
      validate: [
        {
          validator: Number.isFinite,
          message: "Review count must be a valid number",
        },
        {
          validator: Number.isInteger,
          message: "Review count must be a whole number",
        },
      ],
    },

    // ============================================================
    // SALE BADGE
    // ============================================================

    // Generated by the pricing hook
    saleBadge: {
      type: String,
      trim: true,
      maxlength: [30, "Sale badge must not exceed 30 characters"],
      default: "",
    },

    // ============================================================
    // IMAGES
    // ============================================================

    // Cloudinary image URL (primary image)
    image: {
      type: String,
      trim: true,
      default: "",
    },

    // Cloudinary public ID used to manage the primary image
    imagePublicId: {
      type: String,
      trim: true,
      default: "",
    },

    // ============================================================
    // VISIBILITY
    // ============================================================

    isActive: {
      type: Boolean,
      default: true,
    },
  },
  {
    timestamps: true,
  }
);

// ============================================================
// PRICING HOOK
// ============================================================
// Calculates selling price and sale badge before validation.
// ============================================================

productSchema.pre("validate", function () {
  const hasOriginalPrice =
    this.originalPrice !== null &&
    this.originalPrice !== undefined &&
    this.originalPrice !== "";

  const discount = this.discountPercentage ?? 0;

  // Discount must be a finite number between 0 and 100.
  if (!Number.isFinite(discount) || discount < 0 || discount > 100) {
    this.invalidate(
      "discountPercentage",
      "Discount must be between 0 and 100"
    );
    return;
  }

  // A discount requires an original price.
  if (discount > 0 && !hasOriginalPrice) {
    this.invalidate(
      "originalPrice",
      "Original price is required when a discount is applied"
    );
    return;
  }

  // Calculate selling price when an original price is provided.
  if (hasOriginalPrice) {
    if (
      typeof this.originalPrice !== "number" ||
      !Number.isFinite(this.originalPrice) ||
      this.originalPrice < 0
    ) {
      this.invalidate(
        "originalPrice",
        "Original price must be a valid non-negative number"
      );
      return;
    }

    const calculatedPrice =
      this.originalPrice * (1 - discount / 100);

    // Round to two decimal places to avoid common floating-point errors.
    this.price =
      Math.round((calculatedPrice + Number.EPSILON) * 100) / 100;

    this.saleBadge = discount > 0 ? `-${discount}%` : "";
  } else {
    // No discount pricing: preserve the supplied selling price.
    this.saleBadge = "";
  }
});

// ============================================================
// INDEXES
// ============================================================

// Text search across product names and descriptions.
productSchema.index({
  name: "text",
  description: "text",
});

// Category filtering.
productSchema.index({
  category: 1,
});

// Newest products first.
productSchema.index({
  createdAt: -1,
});

// Storefront filtering and sorting.
productSchema.index({
  isActive: 1,
  createdAt: -1,
});

// Highest-rated active products.
productSchema.index({
  isActive: 1,
  rating: -1,
});

// Avoid recompiling the model during Next.js development reloads.
const Product =
  mongoose.models.Product ||
  mongoose.model("Product", productSchema, "products");

export default Product;